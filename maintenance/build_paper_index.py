"""Validate the CVPR queue and build a deterministic Markdown paper directory."""
import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'papers' / 'CVPR2026'
TOPICS = {'3d-vision': '3D 视觉', 'generation': '生成模型', 'multimodal': '多模态',
          'recognition': '识别与理解', 'segmentation': '分割与检测', 'video': '视频',
          'medical': '医学视觉', 'robotics': '机器人与自动驾驶', 'theory': '学习方法',
          'imaging': '计算成像', 'other': '其他', 'unclassified': '待精读分类'}
SECTIONS = ['一句话总结', '研究背景与动机', '方法总览', '核心创新与关键设计',
            '实验与关键结果', '消融实验与证据强度', '局限与讨论', '复现提示', '相关工作与阅读顺序', '来源与校验']


def validate(manifest, root=ROOT):
    papers = manifest['papers']
    if len(papers) != manifest['listed_count']:
        raise ValueError('Count mismatch')
    ids, urls, paths = set(), set(), set()
    for r in papers:
        if r['id'] in ids or r['url'] in urls:
            raise ValueError('Duplicate ID or URL')
        ids.add(r['id']); urls.add(r['url'])
        if r['topic'] not in TOPICS or r['status'] not in {'queued', 'reading', 'draft', 'reviewed', 'blocked'}:
            raise ValueError('Unknown topic or status')
        if not r['url'].startswith('https://openaccess.thecvf.com/content/CVPR2026/html/'):
            raise ValueError('Non-main-conference source')
        if r['status'] == 'reviewed':
            path = (root / (r['note_path'] or '')).resolve()
            if not path.is_relative_to((root / 'papers' / 'CVPR2026').resolve()) or not path.is_file():
                raise ValueError('Missing or escaping note')
            if path in paths:
                raise ValueError('Shared note path')
            paths.add(path)
            text = path.read_text(encoding='utf-8')
            if not all('## '+s in text for s in SECTIONS):
                raise ValueError(f'Incomplete sections: {path}')
            if r['url'] not in text or not re.fullmatch('[0-9a-f]{64}', r.get('pdf_sha256', '')):
                raise ValueError('Missing source evidence')
            if r.get('validation') != 'original-read-and-self-reviewed;not-reproduced' or not r['checked_on']:
                raise ValueError('Missing review scope')
    return Counter(r['status'] for r in papers)


def render(m):
    counts = validate(m)
    out = ['<!-- Generated by maintenance/build_paper_index.py -->', '# CVPR 2026 全量论文目录', '',
           f"官方公开主会清单：{len(m['papers'])} 篇；讲解自检完成：{counts['reviewed']} 篇。queued 仅为元数据，不是讲解。", '',
           f"正文与配图本轮联合返工：{sum(r.get('method_revision') == 'completed' and r.get('figure_revision') == 'completed' for r in m['papers'])}/{counts['reviewed']}。历史reviewed计数不等于详细版返工完成。", '',
           '[阅读入口与范围](README.md) · [续做记录](progress.md)', '', '## 已有讲解（返工状态见进度）', '']
    for topic, label in TOPICS.items():
        done = [r for r in m['papers'] if r['status'] == 'reviewed' and r['topic'] == topic]
        if done:
            out.extend(['### '+label, ''])
            for r in done:
                relative = Path(r['note_path']).relative_to('papers/CVPR2026').as_posix()
                out.append(f"- [{r['title']}]({relative})")
            out.append('')
    out.extend(['## 全量队列', '', '标题可在本文件搜索；主题只在阅读后确认。', '', '| 论文 | 状态 | 分类 |', '| --- | --- | --- |'])
    for r in m['papers']:
        title = r['title'].replace('|', '&#124;').replace('[', '&#91;').replace(']', '&#93;')
        out.append(f"| [{title}]({r['url']}) | {r['status']} | {TOPICS[r['topic']]} |")
    return '\n'.join(out)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--write', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    m = json.loads((BASE / 'manifest.json').read_text(encoding='utf-8'))
    result = render(m)
    path = BASE / 'index.md'
    if args.write:
        if path.exists() and not path.read_text(encoding='utf-8').startswith('<!-- Generated by maintenance/build_paper_index.py -->'):
            raise ValueError('Refusing to overwrite a manually authored index')
        path.write_text(result, encoding='utf-8')
    elif args.check and (not path.exists() or path.read_text(encoding='utf-8') != result):
        raise SystemExit('Paper index is stale')
    print(dict(validate(m)))


if __name__ == '__main__':
    main()
