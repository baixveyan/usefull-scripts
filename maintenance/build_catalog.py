"""Generate categorized navigation from catalog.json; preview by default."""
from __future__ import annotations

import argparse
import difflib
import json
from pathlib import Path
from urllib.parse import quote

from validate_catalog import validate

HEADER = '<!-- Generated by maintenance/build_catalog.py; edit catalog.json instead. -->'
CATEGORIES = {'datasets': '论文与数据集', 'app-helpers': '软件辅助', 'booking-helpers': '预约与提醒', 'everyday': '日常实用'}
SUBCATEGORIES = {'vision': '计算机视觉', 'time-series': '时间序列', 'scientific': '科学研究',
                 'tooling': '下载工具', 'translation': '翻译', 'export': '导出与归档',
                 'privacy': '隐私', 'workflow': '工作流', 'appointments': '预约', 'files': '文件', 'network': '网络'}
STATUSES = {'unreviewed': '未审核', 'documented': '资料已核对', 'tested': '限定环境测试通过',
            'needs-maintenance': '需要维护', 'archived': '已归档'}


def cell(value):
    return str(value).replace('\\', '\\\\').replace('|', '\\|').replace('\r', ' ').replace('\n', ' ')


def render(entries):
    result = [HEADER, '# 按场景浏览', '',
              '本页从索引自动生成。测试通过仅指条目所述范围，详情请阅读各项说明。', '']
    for category, title in CATEGORIES.items():
        items = [entry for entry in entries if entry['category'] == category]
        if not items:
            continue
        result.extend([f'## {title}', '', '| 场景 | 条目 | 形式 / 语言 | 状态 |', '| --- | --- | --- | --- |'])
        for entry in sorted(items, key=lambda value: (value['subcategory'], value['id'])):
            path = quote('../' + entry['path'], safe='/.-_')
            name = cell(entry['title']).replace('[', '\\[').replace(']', '\\]')
            subcategory = cell(SUBCATEGORIES.get(entry['subcategory'], entry['subcategory']))
            detail = cell(entry['type'] + ' / ' + ', '.join(entry['languages']))
            result.append(f"| {subcategory} | [{name}]({path}) | {detail} | {STATUSES[entry['status']]} |")
        result.append('')
    result.extend(['## 使用与维护', '',
                   '- 完整字段见 [catalog.json](../catalog.json)，分类约定见[分类规范](taxonomy.md)。',
                   '- 运行 `python maintenance/validate_catalog.py` 检查索引和本地入口链接。',
                   '- 运行 `python maintenance/build_catalog.py --check` 检查本页是否与索引同步。',
                   '- 更新索引后运行 `python maintenance/build_catalog.py --write` 重新生成本页。',
                   '- 以上检查不联网，不证明外部链接、安装包或真实服务可用。', ''])
    return '\n'.join(result)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    root = args.root.resolve()
    errors = validate(root)
    if errors:
        print('\n'.join(errors))
        return 2
    target = root / 'docs/catalog.md'
    existing = target.read_text(encoding='utf-8-sig')
    expected = render(json.loads((root / 'catalog.json').read_text(encoding='utf-8-sig'))['entries'])
    if existing == expected:
        print('Navigation is up to date')
        return 0
    if args.write:
        if not existing.startswith(HEADER):
            print('Refusing overwrite: navigation does not have generator marker')
            return 2
        target.write_text(expected, encoding='utf-8', newline='\n')
        print('Updated docs/catalog.md')
        return 0
    if args.check:
        print('Navigation is out of date; run with --write after reviewing index')
        return 1
    print(''.join(difflib.unified_diff(existing.splitlines(True), expected.splitlines(True), fromfile='current', tofile='generated')), end='')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
